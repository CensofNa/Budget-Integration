/**
 * Builds a self-contained, deployable dist/ folder.
 *
 *   npm run build
 *
 * dist/ then contains compiled JS + every workspace package.json (entry points
 * rewritten from .ts to .js) + package-lock.json + prisma schema + a PM2 config
 * that runs plain `node`. Upload dist/ to the server and run:
 *
 *   npm ci --omit=dev && npx prisma generate && pm2 start ecosystem.config.cjs
 *
 * node_modules is NOT shipped: argon2 / Prisma engines must be built on Linux,
 * and npm workspace symlinks don't survive FTP.
 */
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const log = (msg) => console.log(`[build] ${msg}`);

// 1. Clean
rmSync(dist, { recursive: true, force: true });

// 2. Compile
log("tsc -p tsconfig.build.json");
const tsc = spawnSync(process.execPath, [join(root, "node_modules/typescript/bin/tsc"), "-p", "tsconfig.build.json"], {
  cwd: root,
  stdio: "inherit",
});
if (tsc.status !== 0) {
  console.error("[build] tsc failed, dist/ not produced.");
  process.exit(tsc.status ?? 1);
}

// 3. Workspace package.json files, with .ts entry points pointed at the compiled .js
const toJs = (value) => {
  if (typeof value === "string") return value.endsWith(".ts") && !value.endsWith(".d.ts") ? value.replace(/\.ts$/, ".js") : value;
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => key !== "types")
        .map(([key, v]) => [key, toJs(v)]),
    );
  }
  return value;
};

const rootPkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const workspaceDirs = rootPkg.workspaces.flatMap((pattern) => {
  const base = pattern.replace(/\/\*$/, "");
  return readdirSync(join(root, base), { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(root, base, d.name, "package.json")))
    .map((d) => join(base, d.name));
});

for (const dir of workspaceDirs) {
  const pkg = JSON.parse(readFileSync(join(root, dir, "package.json"), "utf8"));
  for (const field of ["main", "module", "exports"]) {
    if (pkg[field] !== undefined) pkg[field] = toJs(pkg[field]);
  }
  delete pkg.types;
  delete pkg.scripts;
  mkdirSync(join(dist, dir), { recursive: true });
  writeFileSync(join(dist, dir, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
}
log(`copied ${workspaceDirs.length} workspace package.json files`);

// 4. Root package.json + lockfile (kept identical so `npm ci` accepts the lock)
cpSync(join(root, "package.json"), join(dist, "package.json"));
cpSync(join(root, "package-lock.json"), join(dist, "package-lock.json"));

// 5. Prisma schema (client is generated on the server) + SQL functions for reference
cpSync(join(root, "prisma"), join(dist, "prisma"), {
  recursive: true,
  filter: (src) => !src.endsWith(".ts"),
});

// 6. .env.example as a template (never the real .env)
if (existsSync(join(root, ".env.example"))) cpSync(join(root, ".env.example"), join(dist, ".env.example"));

// 7. PM2 config that runs compiled JS with plain node
const require = createRequire(import.meta.url);
const pm2 = require(join(root, "ecosystem.config.cjs"));
const apps = pm2.apps.map(({ script, args, ...rest }) => ({
  ...rest,
  script: args.replace(/\.ts$/, ".js"),
  cwd: "__CWD__",
}));
const pm2Source = `/**
 * Generated by scripts/build-dist.mjs. Edit ecosystem.config.cjs in the repo instead.
 *   First start:  pm2 start ecosystem.config.cjs && pm2 save
 *   Update:       pm2 reload ecosystem.config.cjs
 */
module.exports = ${JSON.stringify({ apps }, null, 2).replaceAll('"__CWD__"', "__dirname")};
`;
writeFileSync(join(dist, "ecosystem.config.cjs"), pm2Source);

for (const app of apps) {
  if (!existsSync(join(dist, app.script))) {
    console.error(`[build] missing entry point for ${app.name}: ${app.script}`);
    process.exit(1);
  }
}
log(`done -> ${relative(process.cwd(), dist) || "dist"} (${apps.map((a) => a.name).join(", ")})`);
